#!/usr/bin/env bash
#
# Galmaster SSO — one-shot installer
#
#   curl -fsSL https://raw.githubusercontent.com/Lbcheng1145/galmaster-sso/main/scripts/setup.sh | bash
#
# or, with options:
#
#   SSO_DIR=/opt/sso SSO_AUTH_HOST=auth.example.com SSO_OWNER_EMAIL=me@example.com \
#     bash scripts/setup.sh
#
# Safe to run repeatedly: an existing config, data directory and installed
# dependencies are never overwritten.

set -euo pipefail

DIR="${SSO_DIR:-/opt/sso}"
AUTH_HOST="${SSO_AUTH_HOST:-auth.example.com}"
RP_ID="${SSO_RP_ID:-}"
RP_NAME="${SSO_RP_NAME:-Galmarster SSO}"
OWNER_EMAIL="${SSO_OWNER_EMAIL:-owner@example.com}"
PORT="${SSO_PORT:-3081}"
REPO="${SSO_REPO:-https://github.com/Lbcheng1145/galmaster-sso.git}"
BRANCH="${SSO_BRANCH:-main}"
DO_SYSTEMD="${SSO_SYSTEMD:-yes}"
DO_START="${SSO_START:-yes}"
RUN_USER="${SSO_USER:-$(id -un)}"

c_reset=$'\\033[0m'; c_ok=$'\\033[32m'; c_warn=$'\\033[33m'; c_err=$'\\033[31m'; c_dim=$'\\033[2m'
say()  { printf '%s==>%s %s\\n' "$c_dim" "$c_reset" "$*"; }
ok()   { printf '%s  ok%s %s\\n' "$c_ok" "$c_reset" "$*"; }
warn() { printf '%s  !!%s %s\\n' "$c_warn" "$c_reset" "$*"; }
die()  { printf '%s  xx%s %s\\n' "$c_err" "$c_reset" "$*" >&2; exit 1; }

# ---------------------------------------------------------------- preflight
say "preflight"

command -v node >/dev/null 2>&1 || die "node not found — install Node.js 18 or newer"
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
[ "$NODE_MAJOR" -ge 18 ] || die "node $(node -v) is too old, need >= 18"
ok "node $(node -v)"

command -v npm >/dev/null 2>&1 || die "npm not found"
ok "npm $(npm -v)"

if [ -z "$RP_ID" ]; then
  # registrable suffix: last two labels of the auth host
  RP_ID="$(printf '%s' "$AUTH_HOST" | awk -F. '{ if (NF<=2) print $0; else print $(NF-1)"."$NF }')"
fi
ok "auth host $AUTH_HOST  (rp id $RP_ID)"

# ---------------------------------------------------------------- code
say "code at $DIR"

if [ -f "$DIR/src/gateway.mjs" ]; then
  ok "already present, leaving it alone"
else
  mkdir -p "$DIR"
  if command -v git >/dev/null 2>&1 && git clone --depth 1 --branch "$BRANCH" "$REPO" "$DIR" 2>/dev/null; then
    ok "cloned $REPO"
  else
    die "could not fetch the repository and no existing checkout at $DIR"
  fi
fi

# ---------------------------------------------------------------- config
say "configuration"

CFG="$DIR/src/config.mjs"
if [ -f "$CFG" ]; then
  ok "config.mjs exists, keeping it"
else
  [ -f "$DIR/src/config.example.mjs" ] || die "config.example.mjs missing"
  cat > "$CFG" <<EOF
// Generated by scripts/setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
// Edit freely; this file is git-ignored.

export const config = {
  authHost: '$AUTH_HOST',
  rpId: '$RP_ID',
  rpName: '$RP_NAME',
  ownerEmail: '$OWNER_EMAIL',

  dataDir: '$DIR/data',
  port: $PORT,
  dshLogPath: '',
  totpLabel: 'sso-owner',
  webauthnUser: 'sso-owner',

  cfTeamDomain: '',
  cfAud: '',
  mailerUrl: '',
  magpieKey: '',

  logoutHosts: ['$AUTH_HOST', '$RP_ID'],

  services: {},
  panelTargets: [],
  guard: {},
}
EOF
  chmod 600 "$CFG"
  ok "wrote config.mjs (mode 600)"
  warn "add your services to $CFG before relying on it"
fi

# ---------------------------------------------------------------- deps
say "dependencies"

if [ -d "$DIR/node_modules/@simplewebauthn/server" ]; then
  ok "already installed"
else
  ( cd "$DIR" && npm install --omit=dev --no-audit --no-fund >/dev/null 2>&1 ) \
    || die "npm install failed"
  ok "installed"
fi

# ---------------------------------------------------------------- data
say "data directory"

mkdir -p "$DIR/data"
chmod 700 "$DIR/data"
if [ -f "$DIR/data/session.key" ]; then
  ok "existing keys kept"
else
  ok "will be created on first start"
fi

# ---------------------------------------------------------------- systemd
if [ "$DO_SYSTEMD" = "yes" ] && [ "$(id -u)" -eq 0 ] && command -v systemctl >/dev/null 2>&1; then
  say "systemd"
  cat > /etc/systemd/system/galmaster-sso.service <<EOF
[Unit]
Description=Galmarster SSO gateway
After=network.target

[Service]
Type=simple
WorkingDirectory=$DIR
ExecStart=$(command -v node) $DIR/src/gateway.mjs
Restart=always
RestartSec=3
User=$RUN_USER
Group=$RUN_USER
StandardOutput=append:/var/log/sso.log
StandardError=append:/var/log/sso.log

[Install]
WantedBy=multi-user.target
EOF
  chown -R "$RUN_USER:$RUN_USER" "$DIR" 2>/dev/null || true
  systemctl daemon-reload
  systemctl enable galmaster-sso >/dev/null 2>&1 || true
  systemctl restart galmaster-sso
  sleep 2
  systemctl is-active --quiet galmaster-sso && ok "service running" || die "service failed to start — journalctl -u galmaster-sso -n 50"
else
  warn "skipping systemd (SSO_SYSTEMD=$DO_SYSTEMD, uid $(id -u))"
fi

# ---------------------------------------------------------------- verify
say "verification"

if command -v ss >/dev/null 2>&1 && ss -ltn 2>/dev/null | grep -q ":$PORT "; then
  if [ ! -f "$DIR/gateway.pid" ]; then
    warn "port $PORT is already in use by another process"
  fi
fi

if [ "$DO_START" = "yes" ] && [ "$DO_SYSTEMD" != "yes" ]; then
  if [ -f "$DIR/gateway.pid" ]; then
    kill "$(cat "$DIR/gateway.pid")" 2>/dev/null || true
    sleep 1
  fi
  ( cd "$DIR" && nohup node src/gateway.mjs > "$DIR/gateway.log" 2>&1 & echo $! > "$DIR/gateway.pid" )
  sleep 2
  ok "started in background (pid $(cat "$DIR/gateway.pid"))"
fi

if curl -fsS -m 5 -H "Host: $AUTH_HOST" "http://127.0.0.1:$PORT/healthz" >/dev/null 2>&1; then
  ok "healthz responds on 127.0.0.1:$PORT"
else
  warn "healthz did not respond"
  if [ -f "$DIR/gateway.log" ]; then
    tail -6 "$DIR/gateway.log" | sed "s/^/     /" >&2
  fi
fi

echo
ok "done"
echo
echo "  bootstrap key: $(cat "$DIR/data/bootstrap.key" 2>/dev/null || echo '(created on first start)')"
echo
echo "  next: point your tunnel ingress at http://localhost:$PORT,"
echo "        then open https://$AUTH_HOST/auth/setup?key=<bootstrap key>"
echo
